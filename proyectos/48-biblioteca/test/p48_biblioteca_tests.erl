-module(p48_biblioteca_tests).
-include_lib("eunit/include/eunit.hrl").

arbol_de_supervision_test_() ->
  {setup,
   fun() -> {ok, Pid} = p48_biblioteca_sup:start_link(), Pid end,
   fun(Pid) ->
     unlink(Pid),
     exit(Pid, shutdown)
   end,
   fun(_) ->
     [?_assertEqual(pong, p48_biblioteca_server:ping()),
      ?_assert(is_map(p48_biblioteca_server:state()))]
   end}.
